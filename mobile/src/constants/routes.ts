/**
 * A dynamic `[id]` route. The pathname is typed as a plain string so it
 * compiles before `expo start` has regenerated the typed-routes file for new
 * route files (the generated file is not committed).
 */
function recordRoute(pathname: string, id: number): Href {
  return { pathname, params: { id: String(id) } } as Href;
}

/** `(app)/(admin)/staff/[id]`: edit (or view, when `can_manage` is false) a staff member. */
