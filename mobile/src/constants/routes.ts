import type { Href } from 'expo-router';

/**
 * App routes in one place (Expo Router paths; route groups like `(app)` and
 * `(admin)` don't appear in URLs). Every signed-in screen lives under the
 * `(app)` shell group (sidebar + content Stack):
 * - `(app)/index`: the dashboard, the signed-in home
 * - `(app)/switch-user`: the PIN quick-switch (every signed-in user)
 * - `(app)/(admin)/menu/…` (`product.manage`), `(app)/(admin)/staff/…` (`user.manage`)
 * - `(app)/(pos)/customers/…` (everyone; `new` needs `sale.create`)
 * - `(app)/(pos)/sell` (everyone; the cart needs `sale.create`), `(app)/(pos)/sell/checkout` (`sale.create`)
 * - `(app)/(pos)/orders/…` (`sale.create` or `report.view`); `?review=1` opens the Needs review filter;
 *   `orders/[ulid]/refund` (Phase 7) is for users who can start a refund (`sale.create` or `sale.refund`)
 * - `(app)/(pos)/sync-queue` (`sale.create`): the offline sales still to sync (Phase 5)
 * - `(app)/(admin)/printers` (`sale.create` or `settings.manage`); its `new` and `[id]` need `settings.manage`
 * - `(app)/(admin)/settings` (`settings.manage`): receipt settings
 * - `(app)/(admin)/shifts/…` (`report.zread`): the shifts list and a shift's report (Phase 6)
 * - `(app)/(admin)/reports` (`report.view`): sales reports and CSV export (Phase 6); the inventory report (Inventory)
 * - `(app)/(admin)/inventory/…` (`inventory.adjust` or `report.view`): the stock list and a product's stock (Inventory, v1 completion);
 *   `inventory/ingredients/…`: the ingredient side of the `Products | Ingredients` switch (Ingredients, Recipes & Purchasing)
 * - `(app)/(admin)/ingredients/…` (`product.manage`): the ingredient admin
 * - `(app)/(admin)/purchasing/…`: purchase requests and orders (any purchase permission or `report.view`),
 *   receiving (`purchase.receive`), suppliers (any purchase permission; `new` needs `supplier.manage`)
 * - `(app)/device` (every signed-in user): "This tablet", the setup and health screen (Phase 8 §E)
 * - `(app)/(admin)/devices` and `(app)/(admin)/error-log/…` (`system.manage`): admin Devices and the Error log (Phase 8 §E)
 *
 * Typed routes note: the generated `.expo/types/router.d.ts` (SDK 57) lists
 * nested index routes as `/menu/products/index` instead of `/menu/products`
 * (and is only regenerated by `expo start`), so the paths are declared as
 * `Href` here once, instead of being cast at every call site. At runtime
 * `/menu/products` resolves to `(app)/(admin)/menu/products/index.tsx` as usual.
 */

/**
 * A static path typed as a plain string, so it compiles before `expo start`
 * has regenerated the typed-routes file for new route files.
 */
function staticRoute(path: string): Href {
  return path as Href;
}

